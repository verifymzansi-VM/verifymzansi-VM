/**
 * Staff refusals that send the person to verify their authenticator again,
 * recognised by this pattern. error-reasons.test.ts fails unless the database
 * messages the pattern matches are exactly STAFF_SECOND_FACTOR_MESSAGES, and
 * the check fails when a listed one is no longer raised, so rewording one of
 * them (or adding a new one) cannot silently change the redirect. A message
 * that starts with a command's name ("house slots: ...", raised only by
 * internal.grant_house_slots, which the database owner runs) is about another
 * account's setup, not the staff session, so the words must come before any
 * colon.
 */
export const STAFF_SECOND_FACTOR_PATTERN = /^[^:]*(?:second.factor|authenticator app)/;
export const STAFF_SECOND_FACTOR_MESSAGES = [
  "recent second-factor verification required",
  "second-factor verification required after role assignment",
  "staff second-factor verification expired",
  "staff session with second factor required",
  "verified authenticator app required",
] as const;

/**
 * Reasons a database update that is not applied yet will raise (expand, then
 * contract): the website that understands them deploys first, so the live
 * site never meets a reason it cannot word. They are matched like the
 * generated list. Once the update is applied and the generated list is
 * regenerated, the check fails until the reason is removed here, so each
 * entry lives only as long as its update is pending. `added` is the date the
 * entry was written (YYYY-MM-DD): 30 days later, if the database still does
 * not raise it, the check fails too (remove the entry or ship the update).
 */
export const FOUNDATION_UPCOMING_ERROR_REASONS = {
  // None pending.
} as const satisfies Record<string, { codes: readonly string[]; added: string }>;

export type FoundationErrorReason =
  keyof typeof FOUNDATION_ERROR_REASONS | keyof typeof FOUNDATION_UPCOMING_ERROR_REASONS;
type DatabaseError =
  { code?: string | null; details?: string | null; message?: string | null } | null | undefined;

/**
 * The listed reason a database error carries, or null. Where a caller also
 * names the SQLSTATE (`error.code === "PT409" && hasDatabaseReason(...)`), the
 * check refuses a code the list does not record for that reason, so a code
 * changed in the database cannot silently stop the match.
 */
function databaseReason(error: DatabaseError): FoundationErrorReason | null {
  const details = error?.details;
  return typeof details === "string" &&
    (Object.hasOwn(FOUNDATION_ERROR_REASONS, details) ||
      Object.hasOwn(FOUNDATION_UPCOMING_ERROR_REASONS, details))
    ? (details as FoundationErrorReason)
    : null;
}

/** True when the database error carries one of these reasons. */
export function hasDatabaseReason(
  error: DatabaseError,
  ...reasons: readonly FoundationErrorReason[]
): boolean {
  const reason = databaseReason(error);
  return reason !== null && reasons.includes(reason);
}

/** What a map keyed by reasons gives for this database error, if anything. */
export function lookupDatabaseReason<V>(
  map: ReadonlyMap<FoundationErrorReason, V>,
  error: DatabaseError
): V | undefined {
  const reason = databaseReason(error);
  return reason === null ? undefined : map.get(reason);
}

/** True when the database error's message is this listed message. */
export function hasDatabaseMessage(
  error: DatabaseError,
  key: keyof typeof FOUNDATION_ERROR_MESSAGES
): boolean {
  return error?.message === FOUNDATION_ERROR_MESSAGES[key];
}

/** True for a refusal that asks staff to verify their authenticator again. */
export function isStaffSecondFactorRefusal(error: DatabaseError): boolean {
  return STAFF_SECOND_FACTOR_PATTERN.test(error?.message ?? "");
}
