#!/usr/bin/env node
// Draws the site-wide link-preview picture (src/lib/sharing/default-share-image.tsx)
// in workerd with the Workers build of @vercel/og, the renderer the website's
// /opengraph-image route used, and stores the PNG in
// src/lib/sharing/default-share-image-png.ts. The website serves that stored
// PNG, so the main Worker no longer carries the image renderer (M9.9).
//
//   pnpm share-image:default          regenerate after changing the design
//   pnpm share-image:default --check  fail when the stored PNG is out of date
import assert from "node:assert/strict";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { parse } from "smol-toml";
import { createTestHarness } from "wrangler";
import { prepareOffloadOg } from "./prepare-offload-worker.mjs";

const checking = process.argv.length === 3 && process.argv[2] === "--check";
assert.ok(process.argv.length === 2 || checking, "Only --check is supported");
const output = "src/lib/sharing/default-share-image-png.ts";

const offload = parse(await readFile("wrangler.offload.toml", "utf8"));
prepareOffloadOg();
const sandbox = await mkdtemp(path.join(tmpdir(), "vm-share-image-"));
const server = createTestHarness({
  root: sandbox,
  workers: [
    {
      config: {
        name: "vm-default-share-image",
        main: path.resolve("scripts/fixtures/default-share-image-worker.ts"),
        compatibility_date: offload.compatibility_date,
        compatibility_flags: offload.compatibility_flags,
        alias: Object.fromEntries(
          Object.entries(offload.alias).map(([from, to]) => [from, path.resolve(to)])
        ),
      },
    },
  ],
});
let png;
try {
  await server.listen();
  const response = await server.fetch("https://fixture.invalid/");
  assert.equal(response.status, 200);
  png = Buffer.from(await response.arrayBuffer());
} finally {
  await server.close();
  assert.equal(path.dirname(path.resolve(sandbox)), path.resolve(tmpdir()));
  assert.ok(path.basename(sandbox).startsWith("vm-share-image-"));
  await rm(sandbox, { recursive: true });
}
assert.equal(png.subarray(0, 8).toString("hex"), "89504e470d0a1a0a");
assert.equal(png.readUInt32BE(16), 1200);
assert.equal(png.readUInt32BE(20), 630);

const source = `// Generated by node scripts/generate-default-share-image.mjs; do not edit.
// The site-wide link-preview PNG drawn from ./default-share-image.tsx.
export const DEFAULT_SHARE_IMAGE_PNG_BASE64 =
  "${png.toString("base64")}";
`;
if (checking) {
  const current = await readFile(output, "utf8").catch(() => "");
  if (current.replace(/\r\n/g, "\n") !== source) {
    console.error(`${output} is out of date: run pnpm share-image:default and commit the result.`);
    process.exit(1);
  }
  console.log(`${output} matches the design (${png.length} bytes).`);
} else {
  await writeFile(output, source);
  console.log(`Wrote ${output} (${png.length} bytes).`);
}
