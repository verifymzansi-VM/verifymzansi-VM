import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtemp, readFile, writeFile, unlink, rmdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { format, resolveConfig } from "prettier";
import { parse } from "smol-toml";

const checking = process.argv.length === 3 && process.argv[2] === "--check";
assert.ok(process.argv.length === 2 || checking, "Only --check is supported");
const output = "workers/companion-bindings.d.ts";
for (const name of ["payment-cleanup", "retention-cleanup", "ops-jobs", "site-monitor"]) {
  const config = parse(await readFile(`wrangler.${name}.toml`, "utf8"));
  assert.equal(config.services?.length, 1);
  assert.deepEqual(Object.keys(config.services[0]).sort(), ["binding", "service"]);
  assert.equal(config.services[0].binding, "APP");
  assert.equal(config.services[0].service, "verifymzansi");
  assert.equal(config.vars.APP_URL, "https://verifymzansi.com");
  assert.equal(config.vars.ENVIRONMENT, "production");
  if (["payment-cleanup", "retention-cleanup"].includes(name))
    assert.equal(config.vars.DATA_BACKEND, "foundation");
}
const temporary = await mkdtemp(path.join(tmpdir(), "vm-companion-types-"));
const emptyEnv = path.join(temporary, "empty.env");
const generated = path.join(temporary, "bindings.d.ts");
try {
  await writeFile(emptyEnv, "", { flag: "wx" });
  const env = Object.fromEntries(
    Object.entries(process.env).filter(([name]) =>
      /^(PATH|PATHEXT|SYSTEMROOT|WINDIR|TEMP|TMP|APPDATA|LOCALAPPDATA|USERPROFILE|HOME|COMSPEC|LANG|CI|NO_COLOR|FORCE_COLOR|SYSTEMDRIVE)$/i.test(
        name
      )
    )
  );
  const child = spawnSync(
    process.execPath,
    [
      path.resolve("node_modules/wrangler/bin/wrangler.js"),
      "types",
      generated,
      "--config",
      "wrangler.payment-cleanup.toml",
      "--env-interface",
      "FoundationCompanionBindings",
      "--include-runtime=false",
      "--strict-vars=false",
      "--env-file",
      emptyEnv,
    ],
    {
      env: { ...env, WRANGLER_SEND_METRICS: "false", WRANGLER_SEND_ERROR_REPORTS: "false" },
      encoding: "utf8",
      windowsHide: true,
    }
  );
  assert.equal(child.status, 0, "Wrangler companion type generation failed");
  let source = (await readFile(generated, "utf8")).replaceAll("\r\n", "\n");
  source = source.replace(
    /^\/\/ Generated by Wrangler.*\n/m,
    "// Generated by node scripts/generate-companion-types.mjs; do not edit.\n"
  );
  assert.equal([...source.matchAll(/mainModule: typeof import\("[^"]+"\);/g)].length, 1);
  source = source.replace(
    /mainModule: typeof import\("[^"]+"\);/,
    'mainModule: typeof import("./payment-cleanup");'
  );
  // Keep Cloudflare runtime declarations out of the Next/browser global scope.
  source =
    'import type { Fetcher } from "@cloudflare/workers-types";\n' +
    source +
    "\nexport type { FoundationCompanionBindings };\n";
  source = await format(source, { ...(await resolveConfig(output)), filepath: output });
  if (checking)
    assert.equal(
      (await readFile(output, "utf8")).replaceAll("\r\n", "\n"),
      source,
      "Regenerate companion bindings"
    );
  else await writeFile(output, source);
  console.log(`Companion binding types ${checking ? "verified" : "generated"}.`);
} finally {
  for (const file of [emptyEnv, generated]) {
    try {
      await unlink(file);
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
  await rmdir(temporary);
}
