#!/usr/bin/env node
/**
 * preflight-cloudflare.js
 *
 * Quick pre-check before running any OpenNext / Cloudflare build commands.
 * On native Windows (no WSL) the build will fail with:
 *   Error: EPERM: operation not permitted, symlink ...
 * because creating symlinks requires elevated privileges on Windows.
 *
 * This script detects the platform early and prints a clear error instead
 * of letting the build crash halfway through.
 *
 * 2026-03-01 — Confirmed: build must run from WSL 2 native ext4 filesystem
 *   (~/verifymzansi), NOT from /mnt/c/... NTFS mount. The NTFS mount causes
 *   EACCES rename errors during pnpm install and symlink failures during
 *   OpenNext bundling. Copy project with rsync then build from ~.
 */

const os = require("os");
const fs = require("fs");
const path = require("path");

const args = new Set(process.argv.slice(2));
const validateOnly = args.has("--validate-only");

const repoRoot = path.join(__dirname, "..");
const wranglerTomlPath = path.join(repoRoot, "wrangler.toml");
const openNextEntryPath = path.join(repoRoot, "workers", "open-next-entry.mjs");
const envLocalPath = path.join(repoRoot, ".env.local");
const envProductionLocalPath = path.join(repoRoot, ".env.production.local");

const blockedProductionVars = [
  "BYPASS_OTP_CODE",
  "TEST_PHONE_NUMBERS",
  "ENABLE_MOCK_OZOW",
  "ENABLE_DEV_PAYMENT_BYPASS",
  "ENABLE_DEV_KYC_WEBHOOK_BYPASS",
  "ENABLE_TEST_POSTING_BYPASS",
  "NEXT_PUBLIC_ENABLE_TEST_POSTING_BYPASS",
  "ENABLE_DEV_TURNSTILE_BYPASS",
  "DEV_EXPOSE_OTP",
  "SMS_MOCK",
  "PLAYWRIGHT_TEST_MODE",
];

function readText(filePath) {
  try {
    return fs.readFileSync(filePath, "utf8");
  } catch (error) {
    return null;
  }
}

function validateCloudflareConfig() {
  const errors = [];

  const wranglerToml = readText(wranglerTomlPath);
  if (!wranglerToml) {
    errors.push(`Missing required Cloudflare config: ${wranglerTomlPath}`);
  }

  const openNextEntry = readText(openNextEntryPath);
  if (!openNextEntry) {
    errors.push(`Missing required Cloudflare worker entrypoint: ${openNextEntryPath}`);
  }

  if (wranglerToml) {
    if (!/main\s*=\s*"workers\/open-next-entry\.mjs"/.test(wranglerToml)) {
      errors.push("wrangler.toml must set main = \"workers/open-next-entry.mjs\".");
    }

    const requiredBindings = [
      { name: "NEXT_CACHE_DO_QUEUE", className: "DOQueueHandler" },
      { name: "NEXT_TAG_CACHE_DO_SHARDED", className: "DOShardedTagCache" },
      { name: "NEXT_CACHE_DO_PURGE", className: "BucketCachePurge" },
      { name: "RATE_LIMITER_DO", className: "RateLimiterDO" },
    ];

    for (const { name, className } of requiredBindings) {
      const bindingPattern = new RegExp(`name\\s*=\\s*"${name}"\\s*,\\s*class_name\\s*=\\s*"${className}"`);
      if (!bindingPattern.test(wranglerToml)) {
        errors.push(`wrangler.toml is missing Durable Object binding ${name} -> ${className}.`);
      }
    }
  }

  if (openNextEntry) {
    const requiredExports = ["DOQueueHandler", "DOShardedTagCache", "BucketCachePurge", "RateLimiterDO"];
    for (const exportName of requiredExports) {
      if (!new RegExp(`export\\s*\\{[^}]*\\b${exportName}\\b[^}]*\\}`).test(openNextEntry)) {
        errors.push(`workers/open-next-entry.mjs must re-export ${exportName}.`);
      }
    }

    if (!/export\s+default\s+worker\s*;/.test(openNextEntry)) {
      errors.push("workers/open-next-entry.mjs must default-export the generated OpenNext worker.");
    }
  }

  return errors;
}

function writeProductionEnvOverride() {
  const overrideLines = [
    "# Auto-generated by scripts/preflight-cloudflare.js",
    "# Prevent dev-only bypass variables from leaking into production builds.",
  ];

  const envLocal = readText(envLocalPath);
  const foundBlockedVars = new Set();

  if (envLocal) {
    for (const variableName of blockedProductionVars) {
      const pattern = new RegExp(`^\\s*${variableName}\\s*=`, "m");
      if (pattern.test(envLocal)) {
        foundBlockedVars.add(variableName);
      }
    }
  }

  for (const variableName of blockedProductionVars) {
    overrideLines.push(`${variableName}=`);
  }

  fs.writeFileSync(envProductionLocalPath, `${overrideLines.join("\n")}\n`, "utf8");

  if (foundBlockedVars.size > 0) {
    console.log(
      `✓ Neutralized dev-only env vars for production build: ${Array.from(foundBlockedVars).join(", ")}`
    );
  } else {
    console.log("✓ Wrote production env override to block dev-only bypass variables.");
  }
}

function isWSL() {
  if (os.platform() !== "linux") return false;
  try {
    const release = os.release().toLowerCase();
    return release.includes("microsoft") || release.includes("wsl");
  } catch {
    return false;
  }
}

const platform = os.platform();
const validationErrors = validateCloudflareConfig();

if (validationErrors.length > 0) {
  console.error("\nCloudflare config validation failed:\n");
  for (const error of validationErrors) {
    console.error(`- ${error}`);
  }
  process.exit(1);
}

if (validateOnly) {
  console.log("✓ Cloudflare config validation passed.");
  process.exit(0);
}

writeProductionEnvOverride();

if (platform === "win32") {
  console.error(`
╔══════════════════════════════════════════════════════════════╗
║  ❌  Cloudflare build is not supported on native Windows    ║
╠══════════════════════════════════════════════════════════════╣
║                                                              ║
║  OpenNext creates symlinks during bundling, which requires   ║
║  elevated privileges on Windows and will fail with:          ║
║                                                              ║
║    EPERM: operation not permitted, symlink                   ║
║                                                              ║
║  Use one of these alternatives:                              ║
║                                                              ║
║  1. WSL 2 on an ext4 workspace (recommended):                ║
║     wsl -d Ubuntu                                            ║
║     rsync -a --delete /mnt/c/Users/.../verifymzansi/ ~/verifymzansi/ ║
║     cd ~/verifymzansi                                        ║
║     pnpm build:cloudflare                                    ║
║                                                              ║
║  2. Push to master and let GitHub Actions deploy on Ubuntu   ║
║                                                              ║
║  CI/CD deploys on ubuntu-latest — no action needed there.    ║
║                                                              ║
╚══════════════════════════════════════════════════════════════╝
`);
  process.exit(1);
}

// On Linux/macOS/WSL — all good
if (isWSL()) {
  console.log("✓ Running in WSL — Cloudflare build is supported.");
} else if (platform === "darwin") {
  console.log("✓ Running on macOS — Cloudflare build is supported.");
} else {
  console.log(`✓ Running on ${platform} — Cloudflare build should work.`);
}

// Cloudflare's build cache can restore a stale src/proxy.ts from older builds.
// Remove it so Next/OpenNext sees only the active Edge middleware entrypoint.
const staleProxy = path.join(__dirname, "..", "src", "proxy.ts");
if (fs.existsSync(staleProxy)) {
  fs.rmSync(staleProxy);
  console.log("✓ Removed stale src/proxy.ts (restored from build cache).");
}
