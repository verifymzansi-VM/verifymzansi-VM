#!/usr/bin/env node
// BF-06: renders the reviewed reference catalogue (src/lib/domains/taxonomy/reference.json)
// into deterministic reference-table seeds for the native fixture. The SQL is
// generated so the TypeScript registry and database seeds cannot drift; `--check`
// fails when the committed SQL differs from a fresh render.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "src/lib/domains/taxonomy/reference.json";
const SEEDS = "docs/backend-foundation/prototypes/taxonomy-reference-seed.sql";
const raw = readFileSync(SOURCE);
const ref = JSON.parse(raw);
const contentHash = createHash("sha256").update(raw).digest("base64url");

const lit = (value) =>
  value === null || value === undefined ? "null" : `'${String(value).replaceAll("'", "''")}'`;
const json = (value) => (value === undefined ? "null" : `${lit(JSON.stringify(value))}::jsonb`);
const bool = (value) => (value ? "true" : "false");
const normalizeAlias = (value) =>
  value
    .normalize("NFKD")
    .replace(/[()]/g, " ")
    .replace(/[^a-zA-Z0-9\s-]+/g, " ")
    .replace(/[-_]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
// Closed choices, booleans and numeric bounds can be filtered exactly; free text and
// suggestion lists are display-only until a normalisation contract exists.
const facetKind = (field) => {
  if (field.renderer === "boolean") return "boolean";
  if (["number", "money"].includes(field.renderer)) return "range";
  if (field.renderer === "select" && field.optionAuthority === "closed") return "choice";
  if (field.renderer === "checklist" && field.optionAuthority === "closed") return "contains";
  return null;
};
const rows = (table, columns, values) =>
  values.length
    ? `insert into ${table} (${columns.join(", ")}) values\n  ${values
        .map((row) => `(${row.join(", ")})`)
        .join(",\n  ")};\n`
    : "";

const aliases = ref.cities.flatMap((city) =>
  [...new Set(city.aliases.map(normalizeAlias))].map((alias) => [lit(city.id), lit(alias)])
);
const sql = [
  `-- Generated by scripts/build-taxonomy-sql.mjs from ${SOURCE}. Do not edit by hand.`,
  `-- Reference content hash: ${contentHash}`,
  rows(
    "private.reference_catalog_versions",
    ["version", "content_hash"],
    [[ref.version, lit(contentHash)]]
  ),
  rows(
    "private.categories",
    ["key", "kind", "area", "label", "activity_required", "sort_order", "reference_version"],
    ref.categories.map((c, i) => [
      lit(c.key),
      lit(c.kind),
      lit(c.area),
      lit(c.label),
      bool(c.activityRequired),
      i + 1,
      ref.version,
    ])
  ),
  rows(
    "private.category_activities",
    ["category_key", "key", "label", "field_group", "sort_order"],
    ref.activities.map((a, i) => [
      lit(a.category),
      lit(a.key),
      lit(a.label),
      lit(a.fieldGroup ?? null),
      i + 1,
    ])
  ),
  rows(
    "private.provinces",
    ["id", "code", "label", "sort_order"],
    ref.provinces.map((p, i) => [lit(p.id), lit(p.code), lit(p.label), i + 1])
  ),
  rows(
    "private.cities",
    ["id", "province_id", "label", "sort_order"],
    ref.cities.map((c, i) => [lit(c.id), lit(c.province), lit(c.label), i + 1])
  ),
  rows("private.city_aliases", ["city_id", "alias_normalized"], aliases),
  rows(
    "private.category_fields",
    [
      "category_key",
      "key",
      "label",
      "renderer",
      "option_authority",
      "required",
      "validation",
      "options",
      "unit",
      "depends_on",
      "depends_on_values",
      "dynamic_maximum",
      "facet_kind",
      "sort_order",
    ],
    ref.listingFields.map((f, i) => [
      lit(f.category),
      lit(f.key),
      lit(f.label),
      lit(f.renderer),
      lit(f.optionAuthority),
      bool(f.required),
      json(f.validation),
      json(f.options),
      lit(f.unit ?? null),
      lit(f.dependsOn ?? null),
      json(f.dependsOnValues),
      lit(f.dynamicMaximum ?? null),
      lit(facetKind(f)),
      i + 1,
    ])
  ),
].join("\n");

if (process.argv.includes("--check")) {
  if (readFileSync(SEEDS, "utf8") !== sql) {
    console.error("Taxonomy seed SQL is stale; run node scripts/build-taxonomy-sql.mjs");
    process.exit(1);
  }
  console.log(`Taxonomy seed SQL matches reference ${contentHash}`);
} else {
  writeFileSync(SEEDS, sql);
  console.log(
    `Wrote ${SEEDS}: ${ref.categories.length} categories, ${ref.activities.length} activities, ` +
      `${ref.provinces.length} provinces, ${ref.cities.length} cities, ${aliases.length} aliases, ` +
      `${ref.listingFields.length} fields (${ref.listingFields.filter(facetKind).length} facets)`
  );
}
