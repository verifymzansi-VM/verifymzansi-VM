// Generates the shared person-name character rule for the app and the
// foundation database from one Unicode letter/mark table. Both runtimes then
// accept exactly the same names, independent of their own Unicode versions or
// database collation. Run with --check in CI to detect drift.
import { readFileSync, writeFileSync } from "node:fs";
import prettier from "prettier";

const JSON_PATH = "src/lib/foundation/person-name-ranges.json";
const SQL_PATH = "docs/backend-foundation/prototypes/person-name-rule.sql";

function letterMarkRanges() {
  const letterOrMark = /[\p{L}\p{M}]/u;
  const ranges = [];
  let start = -1;
  for (let code = 0; code <= 0x110000; code++) {
    const ok =
      code < 0x110000 &&
      !(code >= 0xd800 && code <= 0xdfff) &&
      letterOrMark.test(String.fromCodePoint(code));
    if (ok && start < 0) start = code;
    if (!ok && start >= 0) {
      ranges.push([start, code - 1]);
      start = -1;
    }
  }
  return ranges;
}

const escape = (code) =>
  code <= 0xffff
    ? "\\u" + code.toString(16).padStart(4, "0")
    : "\\U" + code.toString(16).padStart(8, "0");

export function renderPersonNameSql({ unicode, ranges }) {
  const bracket = ranges
    .map(([lo, hi]) => (lo === hi ? escape(lo) : escape(lo) + "-" + escape(hi)))
    .join("");
  return `-- GENERATED by scripts/generate-person-name-rule.mjs from
-- src/lib/foundation/person-name-ranges.json (Unicode ${unicode} letters and marks).
-- Do not edit by hand. src/lib/foundation/person-name.ts applies the same table.
--
-- A person name is NFC text of 2-50 characters made of Unicode letters and
-- marks, single ASCII spaces between parts, apostrophes, full stops and
-- hyphens. Tabs, newlines, other Unicode spaces, digits, symbols and format
-- characters are refused. Code-point ranges keep the rule independent of the
-- database collation.
create function internal.person_name_valid(p_name text)
returns boolean language sql immutable parallel safe security invoker set search_path=pg_catalog as $$
  select p_name is not null
    and pg_catalog.char_length(p_name) between 2 and 50
    and p_name is nfc normalized
    and p_name operator(pg_catalog.!~) '(^ | $|  )'
    and p_name operator(pg_catalog.~) ('^[' || $r$${bracket} '.-$r$ || ']+$');
$$;
revoke all on function internal.person_name_valid(text) from public,anon,authenticated,service_role;

-- Names a person could mistake for the platform or its staff. ASCII-only case
-- folding mirrors isReservedPersonName in src/lib/foundation/person-name.ts.
create function internal.person_name_reserved(p_name text)
returns boolean language sql immutable parallel safe security invoker set search_path=pg_catalog as $$
  select pg_catalog.translate(p_name,'ABCDEFGHIJKLMNOPQRSTUVWXYZ','abcdefghijklmnopqrstuvwxyz')
    operator(pg_catalog.~) 'verify *mzansi|(^|[^a-z0-9_])(admin|administrator|moderator|support|staff|official)([^a-z0-9_]|$)';
$$;
revoke all on function internal.person_name_reserved(text) from public,anon,authenticated,service_role;
`;
}

const ranges = letterMarkRanges();
const data = { unicode: process.versions.unicode, ranges };
const json = await prettier.format(JSON.stringify(data), {
  ...(await prettier.resolveConfig(JSON_PATH)),
  filepath: JSON_PATH,
});
const sql = renderPersonNameSql(data);
if (process.argv.includes("--check")) {
  const current = JSON.parse(readFileSync(JSON_PATH, "utf8"));
  if (readFileSync(SQL_PATH, "utf8") !== renderPersonNameSql(current))
    throw new Error("person-name-rule.sql is out of date with person-name-ranges.json");
  process.stdout.write("Person name rule is consistent.\n");
} else {
  writeFileSync(JSON_PATH, json);
  writeFileSync(SQL_PATH, sql);
  process.stdout.write(`Wrote ${ranges.length} ranges (Unicode ${data.unicode}).\n`);
}
