-- Reviewed rollback for updates/20261122111209_term_ending_notice.sql.
-- Not part of the replay. Run it only if that update must be undone, after the
-- owner has decided so. Prefer a forward fix.
--
-- It puts back the earlier bodies of internal.claim_supported_notification_outbox
-- and api.run_slot_renewals byte for byte (same signatures, grants and owners),
-- drops internal.queue_term_ending_notices and internal.term_ending_notice_due,
-- and puts back the earlier outbox kind check. A website from the update's pull
-- request keeps working: the earlier claim refuses the new kind and the email
-- job drops it (laterKinds). It refuses (55000) unless the four functions have
-- this update's bodies (a later update changed one: undo that update first),
-- and while any term-ending notice is queued or recorded (the earlier kind
-- check would refuse those rows, and a notice is a record that the member was
-- told: fix forward instead).
begin;
set local lock_timeout='5s';

do $$
declare shape text; queued integer;
begin
  for shape in
    select v.sig||' '||coalesce((select md5(replace(p.prosrc,E'\r\n',E'\n')) from pg_proc p where p.oid=to_regprocedure(v.sig)),'absent')
    from (values ('internal.claim_supported_notification_outbox(text[],integer)'),
      ('api.run_slot_renewals(integer)'),('internal.term_ending_notice_due(uuid,uuid)'),
      ('internal.queue_term_ending_notices(integer)')) v(sig)
  loop
    if shape not in (
        'internal.claim_supported_notification_outbox(text[],integer) 9a4c68c8ba330364831aac3bdf66b2aa',
        'api.run_slot_renewals(integer) 64c3c57229ca6fe6b8163fd8d57dbfcc',
        'internal.term_ending_notice_due(uuid,uuid) ded26ab2db3448a183eeeddd7c8cd467',
        'internal.queue_term_ending_notices(integer) 70a197a68c46e8cb4a1fbc53056e0d86') then
      raise exception 'rollback precondition: % is not this update''s body', shape using errcode='55000';
    end if;
  end loop;
  select count(*) into queued from private.outbox_events where kind='term_ending_notice';
  if queued > 0 then
    raise exception 'term ending notice rollback: % notices were already queued; fix forward', queued
      using errcode='55000';
  end if;
end$$;

